import { test, expect } from "@playwright/test";
import { ConvexHttpClient } from "convex/browser";
import { api } from "../../convex/_generated/api";
import type { Id } from "../../convex/_generated/dataModel";
import { enterDemo } from "../a11y/helpers";

test("Moderator redacts, adds a template note, removes; author Appeals and a second persona reverses", async ({ page, context }) => {
  test.setTimeout(180_000);
  await enterDemo(page, "/moderation");
  const code = await page.evaluate(() => sessionStorage.getItem("owlside_demo_short_code")!);
  const client = new ConvexHttpClient(process.env.NEXT_PUBLIC_CONVEX_URL ?? "http://127.0.0.1:3210");
  await expect(page.getByRole("note")).toContainText("involve you");
  await page.getByTestId("judge-demo-pill").click();
  await page.getByTestId("persona-switch-alex_owl").click();
  const row = page.getByTestId("moderation-row").filter({ hasText: "◆ Identifies me" });
  await row.click();
  await expect(page.getByRole("heading", { name: /^Review ◆/ })).toBeFocused();
  const selected = new URL(page.url()).searchParams.get("item")!;
  const incidentId = selected.slice("incident:".length) as Id<"incidents">;
  await page.getByRole("button", { name: "Redact", exact: true }).click();
  let dialog = page.getByRole("alertdialog");
  await expect(dialog.getByRole("button", { name: "Cancel", exact: true })).toBeFocused();
  await expect(dialog.getByRole("button", { name: "Confirm", exact: true })).toHaveAttribute("aria-disabled", "true");
  await dialog.getByLabel("Exact words").fill("identifying detail");
  await expect(dialog.getByTestId("redaction-preview")).toContainText("[removed by moderators]");
  await dialog.getByRole("button", { name: "Confirm", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await client.mutation(api.incidents.report, { demoShortCode: code, demoPersonaHandle: "maya_cs", incidentId, reason: "false_misleading" });
  await page.goto(`/moderation?item=${encodeURIComponent(selected)}`);
  await expect(page.getByRole("blockquote")).toContainText("[removed by moderators]");
  await page.getByRole("button", { name: "Add note", exact: true }).click();
  dialog = page.getByRole("alertdialog");
  await dialog.getByLabel("Note template").selectOption("inaccurate");
  await dialog.getByRole("button", { name: "Confirm", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("region", { name: "Review pane" })).toContainText("Several Students reported this as inaccurate");
  await page.getByRole("button", { name: "Remove", exact: true }).click();
  dialog = page.getByRole("alertdialog");
  await dialog.getByLabel("Removal reason").selectOption("not_incident");
  await expect(dialog).toContainText("in-app notice only");
  await expect(dialog).toContainText("Logged as remove");
  await dialog.getByRole("button", { name: "Confirm", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  const author = await context.newPage();
  await author.goto(`/profile/moderation?demo=${code}&persona=jordan_me`);
  const notice = author.getByRole("listitem").filter({ hasText: "Removed: Not a campus safety incident" }).filter({ has: author.getByRole("button", { name: "Appeal decision" }) });
  await notice.getByRole("button", { name: "Appeal decision" }).click();
  await author.getByRole("alertdialog").getByLabel("Appeal message").fill("Please review this decision again.");
  await author.getByRole("alertdialog").getByRole("button", { name: "Submit Appeal", exact: true }).click();
  await expect(author.getByRole("alertdialog")).toHaveCount(0);
  await page.getByRole("link", { name: /^Appeals \(/ }).click();
  await expect(page.locator("#main-content")).toContainText("A different Moderator reviews the Appeal");
  await page.getByTestId("judge-demo-pill").click();
  await page.getByTestId("persona-switch-sam_cpe").click();
  const appeal = page.getByRole("article").filter({ hasText: "Please review this decision again." });
  await appeal.getByRole("button", { name: "Show the removed Incident or decision snapshot", exact: true }).click();
  await expect(appeal.getByRole("blockquote")).toContainText("[removed by moderators]");
  await expect(appeal.getByRole("blockquote")).not.toContainText('"text":');
  await appeal.getByRole("button", { name: "Reverse decision", exact: true }).click();
  await expect(page.getByRole("alertdialog")).toContainText("Your answer is final");
  await page.getByRole("alertdialog").getByRole("button", { name: "Confirm", exact: true }).click();
  await expect(appeal).toContainText("Decision reversed");
  await expect(notice).toHaveCount(0);
  await expect(author.locator("#main-content")).toContainText("Decision reversed. Your Appeal is final.");
  await page.getByRole("link", { name: "Action log", exact: true }).click();
  await expect(page.getByRole("table")).toContainText("appeal_reversed");
  await expect(page.getByRole("table")).toContainText("redact");
});

test("Demo maintainer suspension keeps the author’s notices and Appeal reachable", async ({ page, context }) => {
  await enterDemo(page, "/moderation");
  const code = await page.evaluate(() => sessionStorage.getItem("owlside_demo_short_code")!);
  const client = new ConvexHttpClient(process.env.NEXT_PUBLIC_CONVEX_URL ?? "http://127.0.0.1:3210");
  const { postId } = await client.mutation(api.feed.createPost, { demoShortCode: code, demoPersonaHandle: "alex_owl", body: "a sample post for the suspension exercise" });
  await client.mutation(api.moderation.submitReport, { demoShortCode: code, demoPersonaHandle: "sam_cpe", targetType: "post", targetId: postId, reason: "harassment" });
  await page.getByTestId("moderation-row").filter({ hasText: "a sample post for the suspension exercise" }).click();
  await page.getByRole("button", { name: "Suspend author", exact: true }).click();
  await expect(page.getByRole("alertdialog")).toContainText("Clout is reversed");
  await page.getByRole("alertdialog").getByRole("button", { name: "Confirm", exact: true }).click();
  const author = await context.newPage();
  await author.goto(`/profile/moderation?demo=${code}&persona=alex_owl`);
  await expect(author.locator("main")).toContainText("Your account is suspended");
  await author.getByRole("button", { name: "Appeal decision", exact: true }).click();
  await author.getByRole("alertdialog").getByLabel("Appeal message").fill("Please review the suspension.");
  await author.getByRole("alertdialog").getByRole("button", { name: "Submit Appeal", exact: true }).click();
  await expect(author.getByRole("alertdialog")).toHaveCount(0);
  await expect(author.locator("main")).toContainText("Appeal: Open");
  await author.getByRole("button", { name: "Demo · switch to Sam (second Moderator)", exact: true }).click();
  await expect(author.getByTestId("judge-demo-pill")).toContainText("Sam");
});
