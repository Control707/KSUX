export const IDENTIFY_CARD_COPY =
  "I can't help identify people. In an emergency, call 911. To reach KSU Police, or to send an anonymous tip through LiveSafe, open the Emergency Panel.";

/** Phrases Scrappy must never use about campus safety (SPEC-v2 §11). */
