/**
 * Deterministic Scrappy safety gate (SPEC-v2 §11, ADR-0011).
 *
 * Runs on every Ask Scrappy prompt and every `@scrappy` mention BEFORE any
 * quota check and BEFORE any LLM call. On a match the caller returns the fixed,
 * non-AI Safety Card instead of a model answer. This module is pure: it reads no
 * tables, so it cannot reach Incident or Alert records.
 */

export type SafetyGateMatch = "campus_safety" | "identify_person";

export type SafetyCardCitation = {
  entityType: string;
  entityId: string;
  label: string;
  href: string;
};

export type SafetyCard = {
  kind: SafetyGateMatch;
  content: string;
  citations: SafetyCardCitation[];
};

