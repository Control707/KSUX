/** Classify a prompt. Identification wins over a generic safety match. */
export function classifySafetyPrompt(text: string): SafetyGateMatch | null {
  const normalized = text.replace(/[\u2018\u2019]/g, "'").replace(/@scrappy\b/gi, " ");
  if (IDENTIFY_PATTERNS.some((pattern) => pattern.test(normalized))) return "identify_person";
  if (SAFETY_PATTERNS.some((pattern) => pattern.test(normalized))) return "campus_safety";
  return null;
}

export function buildSafetyCard(kind: SafetyGateMatch): SafetyCard {
  return kind === "identify_person"
    ? { kind, content: IDENTIFY_CARD_COPY, citations: [EMERGENCY_PANEL, KSU_POLICE, LIVESAFE] }
    : { kind, content: SAFETY_CARD_COPY, citations: [EMERGENCY_PANEL, SAFETY_PAGE, KSU_POLICE, LIVESAFE] };
}

